import { Octokit } from '@octokit/rest';
import type { ComparisonResult } from '@otel-perf/results-store';
import { exportComparisonToMarkdown } from '@otel-perf/results-store';

export interface GitHubConfig {
  token: string;
  owner: string;
  repo: string;
}

export interface CreateIssueOptions {
  comparison: ComparisonResult;
  prNumber?: number;
  artifactUrl?: string;
  labels?: string[];
}

export interface CreatedIssue {
  number: number;
  url: string;
  title: string;
}

export class IssueCreator {
  private octokit: Octokit;
  private owner: string;
  private repo: string;

  constructor(config: GitHubConfig) {
    this.octokit = new Octokit({ auth: config.token });
    this.owner = config.owner;
    this.repo = config.repo;
  }

  async createBenchmarkIssue(options: CreateIssueOptions): Promise<CreatedIssue> {
    const { comparison, prNumber, artifactUrl, labels = ['performance', 'benchmark'] } = options;

    const title = this.generateTitle(comparison, prNumber);
    const body = this.generateBody(comparison, prNumber, artifactUrl);

    const response = await this.octokit.issues.create({
      owner: this.owner,
      repo: this.repo,
      title,
      body,
      labels,
    });

    return {
      number: response.data.number,
      url: response.data.html_url,
      title: response.data.title,
    };
  }

  async addCommentToIssue(issueNumber: number, body: string): Promise<void> {
    await this.octokit.issues.createComment({
      owner: this.owner,
      repo: this.repo,
      issue_number: issueNumber,
      body,
    });
  }

  async addCommentToPR(prNumber: number, body: string): Promise<void> {
    await this.octokit.issues.createComment({
      owner: this.owner,
      repo: this.repo,
      issue_number: prNumber,
      body,
    });
  }

  private generateTitle(comparison: ComparisonResult, prNumber?: number): string {
    const { summary, target, baseline } = comparison;
    const summaryEmoji = summary === 'improved' ? '🟢' : summary === 'regressed' ? '🔴' : '🟡';

    if (prNumber) {
      return `${summaryEmoji} Performance Benchmark: PR #${prNumber} vs ${baseline.metadata.git.tag || baseline.metadata.label}`;
    }

    return `${summaryEmoji} Performance Benchmark: ${target.metadata.label} vs ${baseline.metadata.label}`;
  }

  private generateBody(
    comparison: ComparisonResult,
    prNumber?: number,
    artifactUrl?: string
  ): string {
    let body = exportComparisonToMarkdown(comparison, {
      artifactUrl,
      includeHeader: true,
    });

    // Add footer
    body += `
---
*Generated by [otel-js-performance-experiments](https://github.com/your-repo)*
`;

    if (prNumber) {
      body += `
Related PR: #${prNumber}
`;
    }

    return body;
  }
}

export async function createIssueFromComparison(
  config: GitHubConfig,
  options: CreateIssueOptions
): Promise<CreatedIssue> {
  const creator = new IssueCreator(config);
  return creator.createBenchmarkIssue(options);
}
